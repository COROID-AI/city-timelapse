import type { BuildingLot } from '../types';

// A single city block laid out on an 80x80 ground plane.
// The cross-streets run along X (east-west) at z=±26 and the main avenue runs
// along Z (north-south) at x=±26. Lots sit in the four quadrants so the camera
// always sees a rich, layered skyline regardless of orbit angle.
//
// Each lot has EXACTLY 6 per-era entries (aligned to ERAS). Heights, facades
// and window glass interpolate continuously; discrete bits (antenna/billboard)
// crossfade via opacity. This is what makes a transition feel like the city is
// literally growing and reskinning.

