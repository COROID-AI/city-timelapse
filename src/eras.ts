/** Convenience: the blended config for a continuous progress in [0,5]. */
export function eraConfigAt(progress: number): EraConfig {
  const i = Math.max(0, Math.min(5, progress));
  const lo = Math.floor(i);
  const hi = Math.min(5, lo + 1);
  const t = i - lo;
  const ids = ['1945', '1965', '1985', '2005', '2025', '2055'] as const;
  if (lo === hi) return ERAS[ids[lo]];
  return lerpEra(ERAS[ids[lo]], ERAS[ids[hi]], t);
}
